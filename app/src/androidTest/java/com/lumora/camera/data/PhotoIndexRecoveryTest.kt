    @Test fun failedRemovalCommitAndEqualRetryKeepTheTombstoneAndIndexTogether() {
        val controlled = CommitControlContext(context, prefs)
        val repository = PhotoRepository(controlled, namespace)
        val candidate = photo("candidate", 10)
        repository.addRecord(candidate)
        controlled.failNextCommit = true
        try {
            repository.removeRecord(candidate)
            fail("An unconfirmed removal must not report success")
        } catch (_: IOException) { }
        assertTrue(repository.getRecoveryStatus().writeUnconfirmed)
        assertTrue(repository.getRecords().isEmpty())
        assertTrue(repository.wasCaptureRemoved(candidate.originalUri, candidate.capturedAt))
        assertNull(repository.removeRecord(candidate))
        assertEquals(3, controlled.commitCalls)
        assertFalse(repository.getRecoveryStatus().writeUnconfirmed)
        val onDisk = durablePreferenceValues()
        assertEquals("[]", onDisk["records"])
        assertEquals(listOf("true"), onDisk.filterKeys { it.startsWith("captureRemoved.") }.values.toList())
    }

    @Test fun failedUndoDoesNotConsumeTheOnlyUndoToken() {
        val controlled = CommitControlContext(context, prefs)
        val repository = PhotoRepository(controlled, namespace)
        val candidate = photo("candidate", 10)
        repository.addRecord(candidate)
        val removal = requireNotNull(repository.removeRecord(candidate))
        assertTrue(repository.wasCaptureRemoved(candidate.originalUri, candidate.capturedAt))
        controlled.failNextCommit = true
        try {
            repository.undoRemoval(removal)
            fail("An unconfirmed undo must not report success")
        } catch (_: IOException) { }
        assertTrue(repository.getRecoveryStatus().writeUnconfirmed)
        repository.undoRemoval(removal)
        assertEquals(4, controlled.commitCalls)
        assertFalse(repository.getRecoveryStatus().writeUnconfirmed)
        assertEquals(listOf(candidate), repository.getRecords())
        assertFalse(repository.wasCaptureRemoved(candidate.originalUri, candidate.capturedAt))
        assertFalse(durablePreferenceValues().keys.any { it.startsWith("captureRemoved.") })
    }

    /** Read native persisted XML, not SharedPreferences' potentially newer in-memory cache. */
    private fun durablePreferenceValues(): Map<String, String> = buildMap {
        val file = File(context.applicationInfo.dataDir, "shared_prefs/$namespace.xml")
        assertTrue("Checked index commits must create their native preference file", file.isFile)
        file.inputStream().use { input ->
            val parser = Xml.newPullParser()
            parser.setInput(input, "UTF-8")
            while (parser.eventType != XmlPullParser.END_DOCUMENT) {
                if (parser.eventType == XmlPullParser.START_TAG) {
                    val key = parser.getAttributeValue(null, "name")
                    if (key != null) {
                        val value = if (parser.name == "string") parser.nextText() else parser.getAttributeValue(null, "value")
                        if (value != null) put(key, value)
                    }
                }
                parser.next()
            }
        }
    }

    private fun recoveryTexts(): Set<Any?> = prefs.all.filterKeys { it.startsWith("recordsRecovery.") }.values.toSet()

    private fun grants() = context.contentResolver.persistedUriPermissions.map {
        Triple(it.uri.toString(), it.isReadPermission, it.isWritePermission)
    }.toSet()

    private fun photo(name: String, time: Long): PhotoRecord = PhotoRecord(
        originalUri = image("$name-source"), enhancedUri = image("$name-render"), styleId = "natural", createdAt = time
    )

    private fun image(name: String): String {
        val file = File(media, "$name.jpg")
        val bitmap = Bitmap.createBitmap(32, 24, Bitmap.Config.ARGB_8888)
        try {
            bitmap.eraseColor(0xff789abc.toInt())
            file.outputStream().use { assertTrue(bitmap.compress(Bitmap.CompressFormat.JPEG, 90, it)) }
        } finally {
            bitmap.recycle()
        }
        return Uri.fromFile(file).toString()
    }

    private fun json(record: PhotoRecord) = JSONObject().apply {
        put("originalUri", record.originalUri)
        put("enhancedUri", record.enhancedUri)
        put("styleId", record.styleId)
        put("createdAt", record.createdAt)
        put("capturedAt", record.capturedAt)
        put("strength", record.strength.name)
        put("intensity", record.intensity.toDouble())
        put("favorite", record.favorite)
        put("sourceOnly", record.sourceOnly)
        put("sourceIsRendered", record.sourceIsRendered)
        put("parentUri", record.parentUri)
    }
}

/** Models commit() returning false AFTER publishing its in-memory map, as Android permits. */
internal class CommitControlContext(base: Context, backing: SharedPreferences) : ContextWrapper(base) {
    var failNextCommit = false
    var commitCalls = 0
    private val controlled = object : SharedPreferences by backing {
        override fun edit(): SharedPreferences.Editor {
            val editor = backing.edit()
            return object : SharedPreferences.Editor by editor {
                // Preserve the wrapper through the fluent critical-index edit chain.
                override fun putString(key: String, value: String?): SharedPreferences.Editor = apply { editor.putString(key, value) }
                override fun putInt(key: String, value: Int): SharedPreferences.Editor = apply { editor.putInt(key, value) }
                override fun putLong(key: String, value: Long): SharedPreferences.Editor = apply { editor.putLong(key, value) }
                override fun commit(): Boolean {
                    commitCalls++
                    if (failNextCommit) {
                        failNextCommit = false
                        editor.apply()
                        return false
                    }
                    return editor.commit()
                }
            }
        }
    }
    override fun getApplicationContext(): Context = this
    override fun getSharedPreferences(name: String, mode: Int): SharedPreferences = controlled
}
