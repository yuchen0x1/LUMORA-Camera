    @Test fun failedCommitIsNotSuccessAndAnEqualRetryStillConfirmsDiskWrite() {
        val controlled = CommitControlContext(context, prefs)
        val repository = PhotoRepository(controlled, namespace)
        val damaged = "{preserve before failed commit"
        assertTrue(prefs.edit().putString("records", damaged).commit())
        val candidate = photo("candidate", 10)
        controlled.failNextCommit = true
        try {
            repository.addRecord(candidate)
            fail("A false commit must propagate an IOException")
        } catch (_: IOException) { }
        assertEquals(1, controlled.commitCalls)
        assertTrue(repository.getRecoveryStatus().writeUnconfirmed)
        assertEquals(listOf(candidate), repository.getRecords())
        assertEquals(setOf(damaged), recoveryTexts())

        // SharedPreferences has already changed its in-memory map, so this is an equal update.
        repository.addRecord(candidate)
        assertEquals("Equality must not bypass a previously unconfirmed disk write", 2, controlled.commitCalls)
        assertFalse(repository.getRecoveryStatus().writeUnconfirmed)
        assertEquals(listOf(candidate), repository.getRecords())
        assertEquals(setOf(damaged), recoveryTexts())
    }

    @Test fun pendingWriteConfirmationRemainsFalseUntilCommitRetrySucceeds() {
        val controlled = CommitControlContext(context, prefs)
        val repository = PhotoRepository(controlled, namespace)
        val candidate = photo("candidate", 10)
        assertTrue(repository.confirmPendingWrite())
        assertEquals(0, controlled.commitCalls)

        controlled.failNextCommit = true
        try {
            repository.addRecord(candidate)
            fail("An unconfirmed index write must not report success")
        } catch (_: IOException) { }
        assertEquals(1, controlled.commitCalls)
        assertTrue(repository.getRecoveryStatus().writeUnconfirmed)
        assertEquals("The failed commit already published the real in-memory map", listOf(candidate), repo.getRecords())

        val reopened = PhotoRepository(controlled, namespace)
        controlled.failNextCommit = true
        assertFalse("Visible records are not proof of a confirmed disk write", reopened.confirmPendingWrite())
        assertEquals(2, controlled.commitCalls)
        assertTrue(reopened.getRecoveryStatus().writeUnconfirmed)
        assertEquals(listOf(candidate), reopened.getRecords())

        assertTrue(reopened.confirmPendingWrite())
        assertEquals(3, controlled.commitCalls)
        assertFalse(repository.getRecoveryStatus().writeUnconfirmed)
        assertEquals(listOf(candidate), repository.getRecords())
        val onDisk = durablePreferenceValues()
        assertEquals(prefs.getString("records", null), onDisk["records"])
        assertEquals(prefs.getLong("recordWriteRevision", 0L).toString(), onDisk["recordWriteRevision"])
        assertTrue(repository.confirmPendingWrite())
        assertEquals("A confirmed write needs no further commit", 3, controlled.commitCalls)
    }

    @Test fun failedRecoveryOffersWriteConfirmationWithoutClaimingRestoredRecords() {
        val controlled = CommitControlContext(context, prefs)
        val repository = PhotoRepository(controlled, namespace)
        val candidate = photo("candidate", 10)
        val backup = JSONArray().put(json(candidate)).toString()
        assertTrue(prefs.edit().putString("recordsRecovery.original", backup).commit())
        val preview = repository.previewIndexRecovery()
        controlled.failNextCommit = true
        val failure = repository.restoreIndexRecovery(preview)
        assertEquals(PhotoIndexRecoveryOutcome.WRITE_NOT_CONFIRMED, failure.outcome)
        assertEquals(0, failure.restoredCount)
        assertEquals(backup, prefs.getString("recordsRecovery.original", null))
        val review = repository.previewIndexRecovery()
        assertTrue(review.writeUnconfirmed)
        assertTrue(review.records.isEmpty())
        val confirmed = repository.restoreIndexRecovery(review)
        assertEquals(PhotoIndexRecoveryOutcome.WRITE_CONFIRMED, confirmed.outcome)
        assertEquals(0, confirmed.restoredCount)
        assertEquals(2, controlled.commitCalls)
        assertFalse(repository.getRecoveryStatus().writeUnconfirmed)
    }

    @Test fun lastCaptureRemovalAndUndoPersistTheirTombstoneWithTheIndex() {
        val candidate = photo("candidate", 10)
        repo.addRecord(candidate)
        val bytes = media.listFiles()!!.associate { it.name to it.readBytes().toList() }
        val removal = requireNotNull(repo.removeRecord(candidate))
        val reopened = PhotoRepository(context, namespace)
        assertTrue(reopened.getRecords().isEmpty())
        assertTrue(reopened.wasCaptureRemoved(candidate.originalUri, candidate.capturedAt))
        assertFalse(reopened.wasCaptureRemoved(candidate.originalUri, candidate.capturedAt + 1))
        assertFalse(reopened.wasCaptureRemoved("different-original", candidate.capturedAt))
        val removedOnDisk = durablePreferenceValues()
        assertEquals("[]", removedOnDisk["records"])
        val tombstones = removedOnDisk.filterKeys { it.startsWith("captureRemoved.") }
        assertEquals(1, tombstones.size)
        assertEquals("true", tombstones.values.single())
        assertFalse(tombstones.keys.single().contains(candidate.originalUri))

        repo.undoRemoval(removal)
        assertEquals(listOf(candidate), reopened.getRecords())
        assertFalse(reopened.wasCaptureRemoved(candidate.originalUri, candidate.capturedAt))
        val restoredOnDisk = durablePreferenceValues()
        assertFalse(restoredOnDisk.keys.any { it.startsWith("captureRemoved.") })
        assertEquals(candidate.enhancedUri, JSONArray(restoredOnDisk["records"]).getJSONObject(0).getString("enhancedUri"))
        assertEquals(bytes, media.listFiles()!!.associate { it.name to it.readBytes().toList() })
    }

    @Test fun removingOneVersionDoesNotMarkOtherVersionsOrAnotherCaptureAsRemoved() {
        val capture = photo("capture", 10)
        val edit = capture.copy(enhancedUri = image("edited"), parentUri = capture.enhancedUri, createdAt = 11)
        val otherCapture = capture.copy(enhancedUri = image("other-capture"), capturedAt = 20, createdAt = 20)
        repo.addRecord(capture)
        repo.addRecord(edit)
        repo.addRecord(otherCapture)
        val editRemoval = requireNotNull(repo.removeRecord(edit))
        assertFalse(repo.wasCaptureRemoved(capture.originalUri, capture.capturedAt))
        repo.undoRemoval(editRemoval)
        requireNotNull(repo.removeRecord(capture))
        assertFalse("The surviving edit still represents this capture", repo.wasCaptureRemoved(capture.originalUri, capture.capturedAt))
        val lastRemoval = requireNotNull(repo.removeRecord(edit))
        assertTrue(repo.wasCaptureRemoved(capture.originalUri, capture.capturedAt))
        assertFalse(repo.wasCaptureRemoved(otherCapture.originalUri, otherCapture.capturedAt))
        assertEquals(listOf(otherCapture), repo.getRecords())
        repo.undoRemoval(lastRemoval)
        assertFalse(repo.wasCaptureRemoved(capture.originalUri, capture.capturedAt))
        assertEquals(listOf(otherCapture, edit), repo.getRecords())
    }

    @Test fun delayedCaptureCompletionKeepsRemovalIntentUntilUndoRestoresTheFinishedVersion() {
        val complete = photo("capture", 10)
        val source = complete.copy(enhancedUri = complete.originalUri, sourceOnly = true)
        repo.addRecord(source)
        val removal = requireNotNull(repo.removeRecord(source))
        PhotoRepository(context, namespace).replaceSourceRecord(complete)
        assertTrue(repo.getRecords().isEmpty())
        assertTrue(repo.wasCaptureRemoved(source.originalUri, source.capturedAt))
