@RunWith(AndroidJUnit4::class)
class PhotoIndexRecoveryTest {
    private val context = InstrumentationRegistry.getInstrumentation().targetContext
    private val namespace = "index-recovery-test-${UUID.randomUUID()}"
    private val prefs = context.getSharedPreferences(namespace, Context.MODE_PRIVATE)
    private val repo = PhotoRepository(context, namespace)
    private val media = File(context.cacheDir, namespace).apply { check(mkdirs()) }

    @After fun cleanup() {
        context.deleteSharedPreferences(namespace)
        // Only files generated by this test, never a library/user MediaStore collection.
        media.deleteRecursively()
    }

    @Test fun previewIsReadOnlyAndDistinguishesEvidenceFromValidatedReadableRecords() {
        val current = photo("current", 20)
        val candidate = photo("candidate", 10)
        val unreadable = photo("unreadable", 9)
        assertTrue(File(Uri.parse(unreadable.originalUri).path!!).delete())
        val entries = JSONArray()
            .put(json(current.copy(favorite = true)))
            .put(json(candidate)).put(json(candidate)).put(json(unreadable))
            .put(json(candidate).put("createdAt", "yesterday"))
            .put("{\"enhancedUri\":\"not an object entry\"}")
            .put(json(candidate).put("originalUri", "https://example.invalid/photo.jpg"))
        assertTrue(prefs.edit().putString("records", JSONArray().put(json(current)).toString())
            .putString("recordsRecovery.valid-array", entries.toString())
            .putString("recordsRecovery.truncated", "{truncated")
            .putInt("recordsRecovery.unrecognized-value", 7).commit())
        val originalPreferences = prefs.all.toMap()
        val originalBytes = media.listFiles()!!.associate { it.name to it.readBytes().toList() }
        val grants = grants()

        assertEquals(PhotoIndexRecoveryStatus(backupCount = 3), repo.getRecoveryStatus())
        val preview = repo.previewIndexRecovery()
        assertEquals(3, preview.backupCount)
        assertFalse(preview.currentIndexDamaged)
        assertEquals(2, preview.malformedSnapshotCount)
        assertEquals(3, preview.invalidEntryCount)
        assertEquals(1, preview.duplicateEntryCount)
        assertEquals(1, preview.alreadyPresentCount)
        assertEquals(0, preview.conflictingRecordCount)
        assertEquals(1, preview.unreadableMediaCount)
        assertEquals(listOf(candidate), preview.records)
        assertFalse(preview.writeUnconfirmed)
        assertEquals(originalPreferences, prefs.all)
        assertEquals(listOf(current), repo.getRecords())
        assertEquals(originalBytes, media.listFiles()!!.associate { it.name to it.readBytes().toList() })
        assertEquals("Recovery must not acquire/revoke app-wide grants", grants, grants())
    }

    @Test fun restoreAppendsReviewedVersionsAndPreservesLatestCurrentObjectsAndBackupText() {
        val current = photo("current", 20)
        val candidate = photo("version", 21).copy(
            originalUri = current.originalUri, capturedAt = current.capturedAt, parentUri = current.enhancedUri
        )
        val backup = JSONArray().put(json(candidate)).toString()
        assertTrue(prefs.edit().putString("records", JSONArray().put(json(current)).toString())
            .putString("recordsRecovery.original", backup).commit())
        val preview = repo.previewIndexRecovery()
        assertEquals(listOf(candidate), preview.records)

        // Another writer changes favorites and adds a capture while the review is open.
        val concurrent = photo("concurrent", 30)
        val currentJson = json(current.copy(favorite = true))
            .put("futureMetadata", JSONObject().put("preserve", "exact current object"))
        assertTrue(prefs.edit().putString("records", JSONArray().put(currentJson).put(json(concurrent)).toString()).commit())
        val bytes = media.listFiles()!!.associate { it.name to it.readBytes().toList() }
        val result = repo.restoreIndexRecovery(preview)
        assertEquals(PhotoIndexRecoveryOutcome.RESTORED, result.outcome)
        assertEquals(1, result.restoredCount)
        assertEquals(listOf(concurrent, candidate, current.copy(favorite = true)), PhotoRepository(context, namespace).getRecords())
        assertEquals(currentJson.toString(), JSONArray(prefs.getString("records", null)).getJSONObject(0).toString())
        assertEquals(backup, prefs.getString("recordsRecovery.original", null))
        assertEquals(1, prefs.all.keys.count { it.startsWith("recordsRecovery.") })
        assertEquals(bytes, media.listFiles()!!.associate { it.name to it.readBytes().toList() })

        val saved = prefs.getString("records", null)
        val again = repo.restoreIndexRecovery(preview)
        assertEquals(PhotoIndexRecoveryOutcome.NOTHING_NEW, again.outcome)
        assertEquals(0, again.restoredCount)
        assertEquals(1, again.alreadyPresentCount)
        assertEquals(saved, prefs.getString("records", null))
    }

    @Test fun restoreRetainsIrrecoverableCurrentEntriesAndEveryOriginalSnapshot() {
        val candidate = photo("candidate", 10)
        val raw = """[null,{"unknown":"keep this evidence"}]"""
        val backup = JSONArray().put(json(candidate)).toString()
        assertTrue(prefs.edit().putString("records", raw)
            .putString("recordsRecovery.readable", backup)
            .putString("recordsRecovery.irrecoverable", "[broken").commit())
        val preview = repo.previewIndexRecovery()
        assertTrue(preview.currentIndexDamaged)
        assertEquals(2, preview.invalidEntryCount)
        assertEquals(1, preview.malformedSnapshotCount)
        assertEquals(listOf(candidate), preview.records)

        assertEquals(PhotoIndexRecoveryOutcome.RESTORED, repo.restoreIndexRecovery(preview).outcome)
        assertEquals(listOf(candidate), repo.getRecords())
        val merged = JSONArray(prefs.getString("records", null))
        assertEquals(3, merged.length())
        assertTrue(merged.isNull(0))
        assertEquals("keep this evidence", merged.getJSONObject(1).getString("unknown"))
        assertEquals(backup, prefs.getString("recordsRecovery.readable", null))
        assertEquals("[broken", prefs.getString("recordsRecovery.irrecoverable", null))
        assertEquals(setOf(raw, backup, "[broken"), recoveryTexts())
        assertTrue("Retained evidence must not be presented as a completely repaired index", repo.getRecoveryStatus().currentIndexDamaged)
    }

