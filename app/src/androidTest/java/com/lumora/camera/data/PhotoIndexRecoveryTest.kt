        assertEquals(4, preview.conflictingRecordCount)
        assertTrue(preview.records.isEmpty())
        assertEquals(PhotoIndexRecoveryOutcome.NOTHING_NEW, repo.restoreIndexRecovery(preview).outcome)
        assertEquals(before, prefs.all)
    }

